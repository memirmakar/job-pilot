// Generates docs/CODEMAP.md: one line per source file with its purpose (the file's first comment line), size,
// exported names with line numbers, and the /api routes it defines. Sessions read this map instead of whole files.
// Run after adding, removing or renaming files or exports: `node tools/codemap.mjs` (also `npm run codemap`).
import fs from "fs";
import path from "path";
import { execSync } from "child_process";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const files = execSync("git ls-files", { cwd: ROOT, encoding: "utf8" }).split("\n")
  .filter((f) => /\.(mjs|js)$/.test(f) && !f.startsWith("node_modules/"));

const GROUPS = [
  ["Server: run, LinkedIn, Claude", (f) => !f.includes("/") && /^(apply|pipeline|tailor|run_notices|profiles|linkedin|linkedin_form|linkedin_guard|applied_sync|easy_apply|llm|llm_daily|llm_reviews|config|store)\.mjs$/.test(f)],
  ["Server: features and routes", (f) => !f.includes("/")],
  ["UI: boot, shell, state", (f) => /^ui\/js\/[^/]+\.js$/.test(f)],
  ["UI: shared components", (f) => f.startsWith("ui/js/components/")],
  ["UI: screens", (f) => f.startsWith("ui/js/screens/")],
  ["Tools", () => true],
];

function describe(f) {
  const src = fs.readFileSync(path.join(ROOT, f), "utf8");
  const lines = src.split(/\r?\n/);
  const purpose = (lines.find((l) => l.startsWith("//")) || "").replace(/^\/\/\s*/, "").slice(0, 150);
  const exps = [], routes = [];
  lines.forEach((l, i) => {
    const n = i + 1;
    let m = l.match(/^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/);
    if (m) exps.push(`${m[1]}:${n}`);
    else if ((m = l.match(/^export\s*\{([^}]*)\}/))) exps.push(`{${m[1].replace(/\s+/g, " ").trim()}}:${n}`);
    for (const r of l.matchAll(/["'`]((?:GET|POST|PUT|DELETE) \/[^"'`\s]*)["'`]\s*:/g)) routes.push(`${r[1]}:${n}`);
  });
  let out = `- \`${f}\` (${lines.length}) ${purpose}`;
  if (exps.length) out += `\n  exports: ${exps.join(" ")}`;
  if (routes.length) out += `\n  routes: ${routes.join(" ")}`;
  return out;
}

const done = new Set();
let md = `# Code map (generated by \`node tools/codemap.mjs\`; don't edit by hand)\n\n` +
  `One line per file: purpose, (line count), exports and routes as name:line. Open files at these lines with Read offset/limit\n` +
  `instead of reading whole files. Regenerate after adding, removing or renaming files or exports.\n`;
for (const [title, test] of GROUPS) {
  const mine = files.filter((f) => !done.has(f) && test(f)).sort();
  if (!mine.length) continue;
  mine.forEach((f) => done.add(f));
  md += `\n## ${title}\n` + mine.map(describe).join("\n") + "\n";
}
fs.mkdirSync(path.join(ROOT, "docs"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "docs", "CODEMAP.md"), md);
console.log(`docs/CODEMAP.md: ${done.size} files, ${Math.round(md.length / 1000)}k chars`);
