// Generates ui/styles/tokens.css from design/tokens.json (the design system's tokens).
// Run after updating tokens.json: node design/gen-tokens.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const T = JSON.parse(fs.readFileSync(path.join(HERE, "tokens.json"), "utf8"));
const OUT = path.join(HERE, "..", "ui", "styles", "tokens.css");

// Tokens the canvas's app.css defines that tokens.json does not (yet)
const EXTRA = {
  mantle: { mocha: "{ctp-mantle}", latte: "{ctp-mantle}" },
  knob: { mocha: "{ctp-text}", latte: "#ffffff" },
};

const colors = Object.fromEntries(T.color.tokens.map((t) => [t.name, t.value]));
Object.assign(colors, EXTRA);
const resolve = (v, theme, depth = 0) => {
  if (typeof v === "object") return resolve(v[theme], theme, depth);
  const m = /^\{(.+)\}$/.exec(v);
  if (!m) return v;
  if (depth > 5 || !colors[m[1]]) throw new Error(`Unresolved token ${v}`);
  return resolve(colors[m[1]], theme, depth + 1);
};
const themed = (theme) => [
  ...Object.keys(colors).filter((n) => !n.startsWith("ctp-")).map((n) => `  --${n}: ${resolve(colors[n], theme)};`),
  ...T.shadow.tokens.map((s) => `  --${s.name}: ${s.value[theme] ?? s.value};`),
  `  color-scheme: ${theme === "mocha" ? "dark" : "light"};`,
  "  /* raw Catppuccin palette: reach for a role token above first */",
  ...Object.keys(colors).filter((n) => n.startsWith("ctp-")).map((n) => `  --${n}: ${resolve(colors[n], theme)};`),
].join("\n");

const shared = [
  ...Object.entries(T.type.families).map(([k, v]) => `  --font-${k}: ${v};`),
  ...T.spacing.tokens.map((s) => `  --${s.name}: ${s.value};`),
  ...T.radius.tokens.map((s) => `  --${s.name}: ${s.value};`),
  ...T.material.tokens.map((s) => `  --${s.name}: ${s.value};`),
].join("\n");

const css = `/* Job Pilot design tokens. GENERATED by design/gen-tokens.mjs from design/tokens.json: do not edit by hand.
   Mocha (dark) is the default; the app sets .jp-mocha or .jp-latte on <html> (see ui/js/theme.js). */
:root, .jp-mocha, .jp-latte {
${shared}
}
:root, .jp-mocha {
${themed("mocha")}
}
.jp-latte {
${themed("latte")}
}
`;
fs.writeFileSync(OUT, css);
console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${css.split("\n").length} lines)`);
